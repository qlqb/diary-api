package com.jungwoo.project.memo.learning.domain;

/**
 * 이 학습 항목에 대해 사용자가 직접 말한 사실. course_topics.user_mark.
 *
 * <p>★ AI는 이 값을 쓰지 않는다. 판단층은 읽기만 하고, 값을 바꾸는 것은 사용자의 명시적
 * 행동(「이미 알아요」/「나중에」)뿐이다. 미룬 횟수 같은 사용 기록으로 자동 조정하지 않는다 —
 * 관찰은 사용자에게 물어볼 근거이지 상태를 바꿀 근거가 아니다.
 *
 * <p>{@link TopicProgressStatus}와 다른 축이다. progress는 "이 앱에서 학습했는가"(앱이
 * 관찰한 사실)이고 여기는 "이미 알고 있는가"(사용자가 말한 사실)다. 앱을 쓰기 전부터 알던
 * 내용은 progress로 표현할 방법이 없다.
 *
 * <p>능력 판정이 아니다. "익숙하다"는 진술이지 "잘한다"가 아니고, 화면 문구도 그렇게 쓴다.
 */
public enum TopicUserMark {

    /** 이미 알고 있다. 이번에도, 다음에도 훑는 정도로 다룬다. */
    KNOWN,

    /** 이번 계획에서는 빼고 나중에 본다. 안다는 뜻이 아니다. */
    DEFER
}
