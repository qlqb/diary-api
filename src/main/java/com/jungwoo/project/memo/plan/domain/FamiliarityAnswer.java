package com.jungwoo.project.memo.plan.domain;

/**
 * 익숙함을 묻는 되묻기에 사용자가 고른 답.
 *
 * <p>★ 세 답의 무게가 다르다. "익숙하다"는 <b>저장할 사실</b>이라 맥락으로 남아 다음 판단의
 * 근거가 되고, "처음이다"는 저장할 것이 없다 — 근거 없음이 이미 기본이고 그때 취급이 이미
 * FULL이다. 이 비대칭을 모르면 "답을 저장한다"는 말이 두 경우 모두를 뜻하는 것처럼 읽히고,
 * 그러면 "처음이에요"를 고른 사용자가 같은 질문을 계속 받게 된다.
 */
public enum FamiliarityAnswer {

    /** 처음 본다. 저장할 상태가 없고, 이번 요청 사슬에서만 다시 묻지 않는다. */
    FIRST_TIME,

    /** 이미 익숙하다. USER_CONFIRMED 맥락으로 저장되어 다음 판단이 근거로 본다. */
    FAMILIAR,

    /**
     * 일부만 익숙하다. 어느 것인지는 이 답으로 알 수 없으므로 저장하지 않는다 —
     * 항목별 「이미 알아요」가 그 자리다. 되묻기만 멈춘다.
     */
    PARTIAL
}
