package com.jungwoo.project.memo.plan.domain;

/**
 * 이 조각의 예상 시간을 얼마나 믿을 수 있는지.
 *
 * <p>v1에서는 사실상 {@link #LOW} 하나다. 시간 추정의 근거가 될 자료 분량(페이지 범위·
 * 슬라이드 수)이 어디에도 저장되지 않기 때문이다(13-plan-judgment.md §2). 값이 갈리지 않는
 * 동안에는 화면에 표시하지 않는다 — 전부 "낮음"인 표시는 정보가 아니라 잡음이다.
 *
 * <p>그래도 계약에 두는 이유는, 분량 정보가 생겼을 때 "그때부터 믿을 만해졌다"를 말할 자리가
 * 미리 있어야 하기 때문이다. 없으면 그 시점에 모든 과거 추정이 소급해 믿을 만해진 것처럼 된다.
 */
public enum EstimateConfidence {

    /** 근거가 항목 제목과 취급뿐이다. 자료 분량을 모른다. */
    LOW,

    /** 자료 분량이나 유형을 알고 계산했다. 분량 정보가 생기면 여기부터다. */
    MEDIUM,

    /** 이 사용자의 실제 소요 기록으로 보정했다. v1은 내지 않는다(속도계수가 아직 없다). */
    HIGH
}
