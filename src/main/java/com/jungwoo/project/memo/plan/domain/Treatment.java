package com.jungwoo.project.memo.plan.domain;

/**
 * 이번 기간에 이 학습 항목을 어떻게 다룰 것인가.
 *
 * "얼마나 잘 아는가"가 아니라 "이번에 무엇을 할 것인가"다. 사용자의 수준을 매기지 않는다 —
 * 같은 항목이 다음 기간에는 다른 취급을 받을 수 있고, 그건 사용자가 변한 게 아니라 상황이
 * 변한 것이다.
 */
public enum Treatment {

    /** 자료 분량대로 제대로 한다. 근거가 없으면 항상 여기다. */
    FULL,

    /** 훑는다. 이미 안다는 근거가 있을 때만. 조각 길이가 짧아진다. */
    SKIM,

    /**
     * 다시 확인한다. 이미 마친 내용을 시험 범위 때문에 다시 볼 때 쓸 자리다.
     *
     * v1에서는 만들지 않는다 — 자리만 있고 판단층이 이 값을 내지 않는다. 실제 요구
     * (시험 범위에 LEARNED 항목 포함)가 들어올 때 켠다.
     */
    REVIEW,

    /** 이번 계획에서 뺀다. 조각을 만들지 않는다. */
    SKIP
}
