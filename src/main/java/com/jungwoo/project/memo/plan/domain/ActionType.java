package com.jungwoo.project.memo.plan.domain;

/**
 * 이 조각에서 실제로 하는 행동.
 *
 * <p>왜 나누는가. "복습하기"는 앉아서 무엇을 할지 사용자가 다시 정해야 하는 말이고, 그
 * 순간 계획은 계획이 아니라 목록이 된다. 행동이 정해져 있어야 시작할 수 있다.
 *
 * <p>그리고 읽기만 있는 계획은 읽기만 하게 만든다. 종류를 나눠 두면 판단·조각 생성이
 * 한쪽으로 쏠렸는지 세어볼 수 있다.
 */
public enum ActionType {

    /** 자료를 읽는다. 반드시 자료와 위치에 anchor해야 한다. */
    READ,

    /** 직접 해 본다(문제 풀이, 코드 작성). 자료 없이도 성립한다. */
    PRACTICE,

    /** 자료를 덮고 떠올린다. 자료 없이도 성립한다. */
    RECALL,

    /** 장비·환경을 실제로 다룬다(설치, 회로, 실습실). 자료 없이도 성립한다. */
    LAB
}
