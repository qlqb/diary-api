package com.jungwoo.project.memo.plan.domain;

/**
 * 계획을 만들지 않고 되묻는 이유.
 *
 * <p>★ 되묻기는 <b>코드가 판정한다</b>. 모델 재량이 아니다. 모델에게 "애매하면 물어봐"라고
 * 맡기면 물어보는 빈도가 프롬프트를 손댈 때마다 바뀌고, 사용자는 어제는 만들어 주던 것을
 * 오늘은 되묻는 이유를 알 수 없다. 조건은 여기 두 가지뿐이고 둘 다 판정 기준이 코드에 있다.
 */
public enum AskReason {

    /**
     * 한 요청에 목표 기간이 둘 이상이다. "시험까지 몰아치고 그 후에는 일상적으로" 같은 요청이
     * 여기 해당한다.
     *
     * <p>계획을 자동으로 둘로 쪼개지 않는다. 두 기간은 목표도 강도도 다른데 그 경계를 서버가
     * 정하면 사용자가 승인하지 않은 계획이 만들어진다. 어느 기간을 지금 잡을지 물어본다.
     */
    MULTI_PERIOD,

    /**
     * 익숙한지 아닌지에 따라 계획 총량이 크게 달라지는데 근거가 하나도 없다.
     *
     * <p>아무 때나 묻지 않는다 — 근거 없는 항목이 있다는 것만으로는 되묻지 않고, 그 항목들을
     * 제대로 볼 때와 훑을 때의 시간 차가 초안 총량의 일정 비율을 넘을 때만 묻는다. 답이
     * 계획을 실제로 바꾸지 않으면 그 질문은 사용자의 시간만 쓴다.
     */
    UNKNOWN_FAMILIARITY
}
