package com.jungwoo.project.memo.plan.provenance;

/**
 * 항목별 근거가 지금도 그 항목을 설명하는가.
 *
 * <p>★ 근거를 지우거나 덮어쓰지 않는다. 상태만 바꾼다 — 사용자가 고친 뒤에도 "고치기 전에는
 * 이런 근거로 제안됐다"가 남아야 무엇이 왜 바뀌었는지 읽을 수 있다(handoff §6).
 */
public enum EvidenceStatus {

    /** 제안된 그대로다. */
    CURRENT,

    /**
     * 사용자가 이 항목의 의미 있는 값을 고쳤다. 아래 근거는 <b>수정 전 제안의 근거</b>다.
     *
     * <p>AI가 다시 검토한 것처럼 보이면 안 된다 — 고친 뒤 모델을 다시 부르지 않는다.
     */
    EDITED_BY_USER,

    /**
     * 근거가 지금 상태를 설명하는지 서버가 판별하지 못했다. 보수적으로 재검토 필요다.
     *
     * <p>날짜·시각을 직접 바꾼 경우가 여기다 — 당시 배치 계산은 그 시각에 대한 것이 아니다.
     */
    NEEDS_REVIEW
}
